def _page(title: str, body: str) -> str:
    return (
        "<!doctype html>\n<html lang=\"en\"><head><meta charset=\"utf-8\">"
        "<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">"
        f"<title>{escape(title)}</title><style>{_CSS}</style></head>"
        f"<body><div class=\"wrap\">{body}"
        "<p class=\"foot\">Generated by EDI MapCheck</p></div></body></html>\n"
    )


def _cell(value: Any) -> str:
    return escape("" if value is None else str(value))


def _badge(text: str, slug: str, big: bool = False) -> str:
    cls = f"badge {slug}" + (" big" if big else "")
    return f'<span class="{cls}">{escape(text)}</span>'


def _bar_rows(items: list[tuple[str, int]]) -> str:
    if not items:
        return '<p class="sub">None.</p>'
    top = max(n for _, n in items) or 1
    rows = []
    for label, n in items:
        width = max(2, round(100 * n / top))
        rows.append(
            f'<div class="bar"><span class="lab">{escape(label)}</span>'
            f'<svg width="220" height="14" role="img">'
            f'<rect width="{width * 2.2:.0f}" height="14" rx="3" fill="#4a72c4"></rect>'
            f'</svg><span class="num">{n}</span></div>'
        )
    return "".join(rows)


def _sparkline(series: list[str]) -> str:
    fill = {"PASS": "#2f9e52", "FAIL": "#d43b3b", "WARNING": "#d79a1e", "NOT_TESTED": "#aab2bd"}
    w, gap = 8, 2
    total = len(series) * (w + gap)
    rects = []
    for i, result in enumerate(series):
        x = i * (w + gap)
        rects.append(
            f'<rect x="{x}" y="0" width="{w}" height="16" rx="2" '
            f'fill="{fill.get(result, "#aab2bd")}"></rect>'
        )
    return f'<svg width="{total}" height="16" role="img">{"".join(rects)}</svg>'


def _findings_table(findings: list) -> str:
    head = (
        "<tr><th>Status</th><th>Row</th><th>Source</th><th>Target</th>"
        "<th>Expected</th><th>Actual</th><th>Category</th><th>Message</th></tr>"
    )
    rows = []
    for f in findings:
        slug = _STATUS_SLUG[f.status]
        rows.append(
            f'<tr class="{slug}"><td>{_badge(f.status.value, slug)}</td>'
            f"<td>{_cell(f.row_id)}</td><td>{_cell(f.source_ref)}</td>"
            f"<td>{_cell(f.target)}</td><td>{_cell(f.expected)}</td>"
            f"<td>{_cell(f.actual)}</td>"
            f"<td>{_cell(f.category.value if f.category else '')}</td>"
            f'<td class="msg">{_cell(f.message)}</td></tr>'
        )
    return f"<table>{head}{''.join(rows)}</table>"


def _counts_and_causes(result: RunResult | InterchangeResult) -> str:
    counts = result.counts
    count_items = [(s.value, counts[s]) for s in _STATUS_ORDER if counts[s]]
    causes = [(c.value, n) for c, n in result.category_counts.items()]
    return (
        '<div class="card"><h2 style="margin-top:0;border:0">Summary</h2>'
        '<div style="display:flex;gap:2rem;flex-wrap:wrap">'
        f'<div style="flex:1 1 260px"><strong>Status counts</strong>{_bar_rows(count_items)}</div>'
        f'<div style="flex:1 1 260px"><strong>Root causes</strong>{_bar_rows(causes)}</div>'
        "</div></div>"
    )


def _header(result: RunResult, overall: Status) -> str:
    slug = _STATUS_SLUG[overall]
    txn = f"{result.transaction_set or ''} {result.transaction_name or ''}".strip()
    return (
        f'<div class="card"><h1>EDI MapCheck report {_badge(overall.value, slug, big=True)}</h1>'
        f'<p class="sub">{escape(result.spec_name or "")}</p>'
        '<dl class="meta">'
        f"<dt>Transaction</dt><dd>{_cell(txn)}</dd>"
        f"<dt>Run at (UTC)</dt><dd>{_cell(result.run_at.strftime('%Y-%m-%d %H:%M:%S'))}</dd>"
        f"<dt>Spec</dt><dd>{_cell(result.spec_path)}</dd>"
        f"<dt>Source</dt><dd>{_cell(result.source_path)}</dd>"
        f"<dt>Output</dt><dd>{_cell(result.output_path)}</dd>"
        "</dl></div>"
    )


def _split_findings(findings: list) -> str:
    """Non-PASS table shown; PASS rows collapsed behind <details>."""
    ordered = sorted(findings, key=lambda f: f.sort_key)
    problems = [f for f in ordered if f.status is not Status.PASS]
    passes = [f for f in ordered if f.status is Status.PASS]
    out = []
    if problems:
        out.append(f'<div class="card">{_findings_table(problems)}</div>')
    else:
        out.append('<div class="card"><p class="sub">No problems — all checks passed.</p></div>')
    if passes:
        out.append(
            f'<details><summary>{len(passes)} passing check(s)</summary>'
            f'<div class="card">{_findings_table(passes)}</div></details>'
        )
    return "".join(out)


def render_run_html(result: RunResult) -> str:
    body = (
        _header(result, result.overall)
        + _counts_and_causes(result)
        + "<h2>Findings</h2>"
        + _split_findings(result.findings)
    )
    return _page(f"MapCheck — {result.spec_name or 'report'}", body)


def render_interchange_html(interchange: InterchangeResult) -> str:
    overall = interchange.overall
    slug = _STATUS_SLUG[overall]
    head = (
        f'<div class="card"><h1>EDI MapCheck interchange report '
        f'{_badge(overall.value, slug, big=True)}</h1>'
        f'<p class="sub">{escape(interchange.spec_name or "")} · '
        f'{len(interchange.documents)} document(s)</p>'
        '<dl class="meta">'
        f"<dt>Spec</dt><dd>{_cell(interchange.spec_path)}</dd>"
        f"<dt>Source</dt><dd>{_cell(interchange.source_path)}</dd>"
        f"<dt>Output</dt><dd>{_cell(interchange.output_path)}</dd>"
        "</dl></div>"
    )
    body = [head, _counts_and_causes(interchange)]
    if interchange.file_findings:
        body.append("<h2>File-level findings</h2>")
        body.append(f'<div class="card">{_findings_table(interchange.file_findings)}</div>')
    body.append("<h2>Documents</h2>")
    for doc in interchange.documents:
        r = doc.result
        dslug = _STATUS_SLUG[r.overall]
        body.append(
            f'<details><summary>{escape(doc.key)} {_badge(r.overall.value, dslug)}</summary>'
            f"{_split_findings(r.findings)}</details>"
        )
    return _page(f"MapCheck interchange — {interchange.spec_name or 'report'}", "".join(body))


def render_trends_html(trends: Trends) -> str:
    if trends.is_empty:
        return _page("MapCheck trends", '<div class="card"><h1>MapCheck trends</h1>'
                     '<p class="sub">No runs recorded yet.</p></div>')
    tiles = (
        '<div class="tiles">'
        f'<div class="tile"><div class="n">{trends.total_runs}</div>'
        '<div class="l">runs</div></div>'
        f'<div class="tile"><div class="n">{trends.overall_pass_rate:.0%}</div>'
        '<div class="l">overall pass rate</div></div>'
        f'<div class="tile"><div class="n">{trends.distinct_specs}</div>'
        '<div class="l">specs tracked</div></div></div>'
    )
    spec_rows = []
    for s in trends.specs:
        slug = _RESULT_SLUG.get(s.latest, "nt")
        spec_rows.append(
            f'<div class="spec-row"><span class="name">{escape(s.spec)}</span>'
            f"{_sparkline(s.series())}"
            f'<span class="rate">{s.pass_rate:.0%}</span>'
            f"{_badge(s.latest, slug)}"
            f'<span class="num">{s.total} run(s)</span></div>'
        )
    causes = f'<div class="card"><h2 style="margin-top:0;border:0">Top root causes</h2>' \
             f'{_bar_rows(trends.top_categories)}</div>'
    body = (
        '<div class="card"><h1>EDI MapCheck — history trends</h1>'
        '<p class="sub">Pass rate per spec over recent runs.</p></div>'
        + tiles
        + f'<div class="card"><h2 style="margin-top:0;border:0">By spec</h2>{"".join(spec_rows)}</div>'
        + causes
    )
    return _page("MapCheck trends", body)


def export_html(result: RunResult | InterchangeResult, path: str | Path) -> Path:
    """Write a single-run (or interchange) HTML report."""
    path = Path(path)
    if isinstance(result, InterchangeResult):
        html = render_interchange_html(result)
    else:
        html = render_run_html(result)
    path.write_text(html, encoding="utf-8")
    return path


def export_trends_html(trends: Trends, path: str | Path) -> Path:
    path = Path(path)
    path.write_text(render_trends_html(trends), encoding="utf-8")
    return path
