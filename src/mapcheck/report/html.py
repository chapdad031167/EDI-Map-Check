"""Self-contained HTML reports (design 010).

Every report is a single file with inline CSS, hand-drawn inline SVG charts,
and no JavaScript — open it in any browser offline, mail it, attach it to a
ticket. Values are HTML-escaped (a report may carry real partner data).
Collapsing uses native ``<details>``; sorting is done by pre-ordering rows.
"""

from __future__ import annotations

from html import escape
from pathlib import Path
from typing import Any

from mapcheck.engine.results import InterchangeResult, RunResult, Status
from mapcheck.report.trends import Trends

_STATUS_ORDER = [Status.FAIL, Status.WARNING, Status.NOT_TESTED, Status.PASS]
_STATUS_SLUG = {
    Status.PASS: "pass", Status.FAIL: "fail",
    Status.WARNING: "warn", Status.NOT_TESTED: "nt",
}
_RESULT_SLUG = {"PASS": "pass", "FAIL": "fail", "WARNING": "warn", "NOT_TESTED": "nt"}

